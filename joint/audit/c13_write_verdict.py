"""Tables of the G-C1.3 verdict from the return package (after the run; not under the stamp).

    python -I audit/c13_write_verdict.py RECORDS OUT.md RECOMPUTE.json [RECOMPUTE.json ...]

Formats the numbers of the returned records and of the author's recomputations (audit/c13_recompute.py; the first
file is the one run with the host's BLAS thread count). It computes nothing that the stamped evaluation did not,
except the durations and the median epoch times read from the logs and histories.
"""
import json
import pathlib
import re
import sys
from datetime import datetime

import numpy as np


def pct(x, d=2):
    return f"{100 * x:.{d}f}%"


def sci(x):
    return "0" if x == 0 else f"{x:.1e}"


def main(rec: pathlib.Path, out: pathlib.Path, *recomputes: pathlib.Path) -> None:
    v = json.loads((rec / "verdict.json").read_text())
    rcs = [(r, json.loads(r.read_text())) for r in recomputes]
    rc = rcs[0][1]
    b = json.loads((rec / "bench.json").read_text())
    cl = json.loads((rec / "check_labels.log").read_text().strip().splitlines()[-1])
    L = []
    w = L.append
    w(f"<!-- generated by audit/c13_write_verdict.py from records/c13/return; config {v['config_sha256']} -->")
    w("")
    w("### Criteria (label-free arm, 128 held-out members)")
    w("")
    w("| Seed | Median of abs(S_pred / S_ref - 1) | Median contact overlap |")
    w("|---|---|---|")
    for i, s in enumerate(("0", "1", "2")):
        w(f"| {s} | {pct(v['per_seed_medians']['abs_S_err'][i], 3)} | {v['per_seed_medians']['iou'][i]:.4f} |")
    w(f"| **Median over seeds** | **{pct(v['C1_value'], 3)}** (C1: at most 5%) | **{v['C2_value']:.4f}** (C2: at least 0.9) |")
    w("")
    w(f"C1 = {v['C1']}; C2 = {v['C2']}; verdict = **{v['verdict']}**. Missing runs: {len(v['missing'])}; non-finite runs: "
      f"{len(v['non_finite'])}. Recomputed by `audit/c13_recompute.py` from the returned predictions and labels: C1 "
      f"{pct(rc['label_free']['C1_value'], 3)}, C2 {rc['label_free']['C2_value']:.4f}, {rc['label_free']['verdict']}.")
    w("")
    w("### Every arm and seed, held-out members (reported)")
    w("")
    w("Medians over the 128 members unless marked; p90 and p10 are the 90th and 10th percentiles.")
    w("")
    w("| Run | abs S error | abs S error, p90 | Contact overlap | Overlap, p10 | Energy gap | Energy-norm error | "
      "Displacement error | Von Mises error | Zero field beaten | Non-negative minimum | alpha | abs S error, rescaled | "
      "Energy gap, rescaled |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, seeds in v["arms"].items():
        for s, r in seeds.items():
            e = r["eval"]
            w(f"| {arm} s{s} | {pct(e['abs_S_err']['median'])} | {pct(e['abs_S_err']['p90'])} | {e['iou']['median']:.3f} | "
              f"{e['iou']['p10']:.3f} | {pct(e['gap']['median'])} | {e['err_K']['median']:.3f} | {pct(e['u_rel_l2']['median'])} | "
              f"{pct(e['vm_rel_l2']['median'], 1)} | {pct(e['zero_field_pass']['mean'], 0)} | "
              f"{sci(e['min_nonneg_over_scale']['min'])} | {e['alpha']['median']:.4f} | "
              f"{pct(e['abs_S_err_rescaled']['median'])} | {pct(e['gap_rescaled']['median'])} |")
    w("")
    w("The non-negative minimum is the smallest non-negative unknown over the 128 members, in units of u_scale: none is "
      "negative.")
    w("")
    w("### The four tested layouts, label-free arm (reported, not judged)")
    w("")
    w("| Layout | S error, seeds 0 / 1 / 2 | Contact overlap, seeds 0 / 1 / 2 | Energy gap, seeds 0 / 1 / 2 |")
    w("|---|---|---|---|")
    for t in ("tested_FS1", "tested_FS2", "tested_FS3", "tested_FS4"):
        m = [v["arms"]["label_free"][s]["tested"][t] for s in ("0", "1", "2")]
        se = " / ".join("%+.2f%%" % (100 * x["S_err"]) for x in m)
        io = " / ".join("%.3f" % x["iou"] for x in m)
        gp = " / ".join(pct(x["gap"]) for x in m)
        w(f"| {t[7:]} | {se} | {io} | {gp} |")
    w("")
    w("### The four tested layouts, every arm and seed (reported, not judged)")
    w("")
    w("| Run | Layout | S error | Contact overlap | Energy gap | Energy-norm error | Displacement error | Von Mises error | "
      "Zero field beaten | Non-negative minimum | alpha | S error, rescaled | Energy gap, rescaled |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, seeds in v["arms"].items():
        for s, r in seeds.items():
            for t in ("tested_FS1", "tested_FS2", "tested_FS3", "tested_FS4"):
                m = r["tested"][t]
                w(f"| {arm} s{s} | {t[7:]} | {100 * m['S_err']:+.2f}% | {m['iou']:.3f} | {pct(m['gap'])} | {m['err_K']:.3f} | "
                  f"{pct(m['u_rel_l2'])} | {pct(m['vm_rel_l2'], 1)} | {'yes' if m['zero_field_pass'] else 'no'} | "
                  f"{sci(m['min_nonneg_over_scale'])} | {m['alpha']:.4f} | {100 * m['S_err_rescaled']:+.2f}% | "
                  f"{pct(m['gap_rescaled'])} |")
    w("")
    w("### Run record")
    w("")
    w(f"- Bench: {b['seconds_per_step_mean']:.4f} s a step on average (median {b['seconds_per_step_median']:.4f}, largest "
      f"{b['seconds_per_step_max']:.4f}), {len(b['losses'])} losses all finite: {b['losses_finite']}; peak memory "
      f"{b['peak_memory_GiB']:.2f} GiB; predicted training time {1430400 * b['seconds_per_step_mean'] / 3600:.1f} h.")
    worst = cl["worst"]
    w(f"- Labels: {cl['labels']} of {cl['instances']}, check ok: {cl['ok']}; worst residuals: "
      + ", ".join(f"{k} {worst[k]:.1e}" for k in worst) + ".")
    starts = {}
    for f in sorted(rec.glob("train_*_s*.log")):
        m = re.search(r"^start (\S+) (\S+ \S+) CST", f.read_text(), flags=re.M)
        starts[m.group(1)] = datetime.strptime(m.group(2), "%Y-%m-%d %H:%M:%S")
    times = [datetime.strptime(" ".join(x.split()[1:4]) + " " + x.split()[-1], "%b %d %H:%M:%S %Y")
             for x in (rec / "train_times.log").read_text().strip().splitlines()]
    order = sorted(starts, key=starts.get)
    w(f"- Training: from {times[0]:%d %B %Y %H:%M:%S} to {times[1]:%d %B %Y %H:%M:%S} (CST, UTC+8), "
      f"{(times[1] - times[0]).total_seconds() / 3600:.1f} h, one attempt per run:")
    w("")
    w("| Run | Started (CST) | Hours | Steps | Seconds per epoch, median | Peak memory (GiB) |")
    w("|---|---|---|---|---|---|")
    for k, name in enumerate(order):
        end = starts[order[k + 1]] if k + 1 < len(order) else times[1]
        h = json.loads((rec / "runs" / name / "history.json").read_text())
        w(f"| {name} | {starts[name]:%H:%M:%S} | {(end - starts[name]).total_seconds() / 3600:.2f} | {h['steps']:,} | "
          f"{float(np.median(h['epoch_seconds'])):.2f} | {h.get('peak_memory_GiB', 0):.2f} |")
    w("")
    w("Hours run from one start to the next and include loading the members and the predictions.")
    w("")
    w("### The author's recomputation (`audit/c13_recompute.py`, records in `records/c13/audit/`)")
    w("")
    e = rc["environment"]
    solver = {"scipy": "scipy's SuperLU, as on the host", "pardiso": "PARDISO, not the host's solver"}[e["resolve_solver"]]
    w(f"- Run with Python {e['python']}, numpy {e['numpy']} and scipy {e['scipy']} (the host had numpy 2.4.6 and scipy "
      f"1.18.0); re-solves with {solver}.")
    for path, r in rcs:
        g = r["regeneration"]
        lw = r["label_free"]["largest_relative_difference_to_returned_metrics"]
        w(f"- `{path.name}`, with the BLAS of numpy and scipy on {g['blas_threads']} threads: {g['instances']} held-out and "
          f"tested instances regenerated with the stamped code; parameters equal: {g['parameters_equal']}; node and "
          f"nonzero counts equal: {g['nodes_and_nnz_equal']}; file SHA-256 equal to the manifest's for "
          f"{g['file_sha256_equal']}. Label-free metrics recomputed for every member and seed: largest relative "
          f"difference to the returned values {max(lw.values()):.1e} over {len(lw)} metrics; C1 "
          f"{pct(r['label_free']['C1_value'], 3)}, C2 {r['label_free']['C2_value']:.4f}, {r['label_free']['verdict']}.")
    g, lab = rc["regeneration"], rc["labels"]
    w(f"- Every returned member is the configured draw: {g['every_returned_member_is_the_configured_draw']}; training and "
      f"held-out members in common: {g['train_eval_overlap']}.")
    w(f"- Returned labels match the ledger: {lab['returned_labels_match_ledger']}; the ledger's instance hashes match the "
      f"manifest: {lab['ledger_instances_match_manifest']}; solver: {', '.join(lab['solvers'])}.")
    for path, r in rcs:
        rs = r["resolves"]
        w(f"- Re-solved {len(rs)} instances ({', '.join(rs)}) in `{path.name}`: bit for bit equal to the returned labels "
          f"{sum(x['bit_identical'] for x in rs.values())} of {len(rs)}; iterations equal to the ledger's: "
          f"{all(x['iterations'] == x['ledger_iterations'] for x in rs.values())}; largest difference "
          f"{max(x['max_du_over_max_u'] for x in rs.values()):.1e} of the largest displacement, "
          f"{max(x['rel_dS'] for x in rs.values()):.1e} in S.")
    ps = rc["label_free"]["per_seed"]
    w("- Label-free predictions: finite in every seed: " + str(all(x["all_finite"] for x in ps.values()))
      + "; smallest non-negative unknown " + ", ".join(sci(x["min_nonneg"]) for x in ps.values())
      + "; share of the non-negative unknowns that are exactly 0 (softplus underflow in float32) "
      + ", ".join(pct(x["nonneg_exactly_zero_share"], 1) for x in ps.values()) + ".")
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(*map(pathlib.Path, sys.argv[1:]))
